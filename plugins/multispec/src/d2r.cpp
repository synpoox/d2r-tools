auto CheckEntries(const D2RL::PluginContext* context, char* report, size_t size) noexcept -> int {
	int bad = 0;
	char list[400] = "";
	size_t used = 0;
	for (const Entry& e : Entries) {
		if (!context->CheckExpectedBytes(e.rva + e.at, e.bytes, e.size)) {
			++bad;
			const int n = std::snprintf(list + used, sizeof(list) - used, " 0x%llx", static_cast<unsigned long long>(e.rva));
			if (n > 0 && static_cast<size_t>(n) < sizeof(list) - used) {
				used += static_cast<size_t>(n);
			}
		}
	}
	const int total = static_cast<int>(sizeof(Entries) / sizeof(Entries[0]));
	if (bad == 0) {
		std::snprintf(report, size, "entry bytes ok: %d functions", total);
	} else {
		std::snprintf(report, size, "entry bytes differ in %d of %d functions:%s", bad, total, list);
	}
	return bad;
}

